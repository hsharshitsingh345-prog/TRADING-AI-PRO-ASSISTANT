"""
Signal Exporter for Telegram / WhatsApp / Webhook.
Generates institutional trade alert templates and JSON payloads for broker APIs (Zerodha, Dhan, TradingView).
"""

import json
from typing import Dict, Any, Optional
from core.models import PrecisionTradePlan, AnalysisOutput, TradeAction


class SignalExporter:
    @staticmethod
    def generate_telegram_alert(
        output: AnalysisOutput,
        options_info: Optional[Dict[str, Any]] = None,
        custom_quantity: Optional[int] = None,
        custom_risk_amount: Optional[float] = None,
        *args,
        **kwargs
    ) -> str:
        """
        Generates a copy-ready institutional Telegram / Discord signal card.
        Accepts flexible arguments to ensure backward and forward compatibility.
        """
        plan = output.primary_trade_plan
        if not plan:
            return "No Active Trade Setup."

        action_icon = "🟢 LONG / BUY" if plan.action == TradeAction.LONG else "🔴 SHORT / SELL"
        ev = plan.ev_result

        qty = custom_quantity if custom_quantity is not None else plan.position_size
        risk_amt = custom_risk_amount if custom_risk_amount is not None else plan.max_risk_amount

        lines = [
            f"⚡ **QUANT-VISION PRO :: INSTITUTIONAL SIGNAL** ⚡",
            f"━━━━━━━━━━━━━━━━━━━━━━━━━",
            f"📊 **Asset:** `{output.asset_name}` ({output.timeframe})",
            f"🎯 **Signal:** {action_icon}",
            f"🏆 **Confluence Score:** `{plan.confluence_score}/100` (Win-Rate: `{ev.win_probability * 100:.1f}%`)",
            f"━━━━━━━━━━━━━━━━━━━━━━━━━",
            f"🔹 **Entry Trigger:** {plan.entry_trigger}",
            f"🛑 **Stop-Loss (SL):** `{plan.stop_loss:.2f}` (Risk: `{plan.risk_points:.2f}` pts)",
            f"🎯 **Target 1 (TP1):** `{plan.target_1:.2f}` (+`{plan.reward_points_1:.2f}` pts | 1:1.5 R:R)",
            f"🚀 **Target 2 (TP2):** `{plan.target_2:.2f}` (+`{plan.reward_points_2:.2f}` pts | 1:2.8 R:R)",
            f"━━━━━━━━━━━━━━━━━━━━━━━━━",
            f"📦 **Quantity / Sizing:** `{qty}` units (Total Risk: ₹`{risk_amt:,.2f}`)"
        ]

        if options_info:
            contract = (
                options_info.get("recommended_contract") or
                options_info.get("options_buying", {}).get("contract") or
                "ATM Strike"
            )
            lots = (
                options_info.get("recommended_lots") or
                options_info.get("user_lots") or
                1
            )
            sl_pts = (
                options_info.get("option_sl_points") or
                options_info.get("options_buying", {}).get("stop_loss_pts") or
                0
            )
            tp1_pts = (
                options_info.get("option_tp1_points") or
                options_info.get("options_buying", {}).get("target_1_pts") or
                "N/A"
            )
            lines.extend([
                f"🏷️ **Recommended Strike:** `{contract}` ({lots} Lots)",
                f"🛡️ **Option SL:** ~`{sl_pts}` pts | **TP1:** `{tp1_pts}`"
            ])

        lines.extend([
            f"━━━━━━━━━━━━━━━━━━━━━━━━━",
            f"⚠️ **Failure Rule:** {plan.failure_condition}",
            f"💡 **Dynamic Trailing:** {plan.target_3_trailing}",
            f"━━━━━━━━━━━━━━━━━━━━━━━━━",
            f"🤖 *Generated by Quant-Vision Pro Institutional AI Engine*"
        ])

        return "\n".join(lines)

    @staticmethod
    def generate_webhook_json(
        output: AnalysisOutput,
        options_info: Optional[Dict[str, Any]] = None,
        custom_quantity: Optional[int] = None,
        custom_risk_amount: Optional[float] = None,
        *args,
        **kwargs
    ) -> str:
        """
        Generates standard JSON payload for automated webhook order execution.
        """
        plan = output.primary_trade_plan
        if not plan:
            return "{}"

        qty = custom_quantity if custom_quantity is not None else plan.position_size
        risk_amt = custom_risk_amount if custom_risk_amount is not None else plan.max_risk_amount

        contract = "N/A"
        lots = 1
        if options_info:
            contract = (
                options_info.get("recommended_contract") or
                options_info.get("options_buying", {}).get("contract") or
                "N/A"
            )
            lots = (
                options_info.get("recommended_lots") or
                options_info.get("user_lots") or
                1
            )

        payload = {
            "source": "Quant-Vision-Pro",
            "asset": output.asset_name,
            "timeframe": output.timeframe,
            "action": "BUY" if plan.action == TradeAction.LONG else "SELL",
            "order_type": "LIMIT",
            "entry_price": plan.entry_price,
            "stop_loss": plan.stop_loss,
            "take_profit_1": plan.target_1,
            "take_profit_2": plan.target_2,
            "quantity": qty,
            "max_risk_currency": risk_amt,
            "confluence_score": plan.confluence_score,
            "options_contract": contract,
            "options_lots": lots
        }
        return json.dumps(payload, indent=2)
